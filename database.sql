CREATE DATABASE IF NOT EXISTS tsn_academy CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE tsn_academy;

CREATE TABLE IF NOT EXISTS users (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(160) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('admin','user') NOT NULL DEFAULT 'user',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS exams (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(80) NOT NULL UNIQUE,
  title VARCHAR(180) NOT NULL,
  tag VARCHAR(100) NOT NULL,
  description TEXT NOT NULL,
  passing_score SMALLINT UNSIGNED NOT NULL,
  duration_minutes SMALLINT UNSIGNED NOT NULL DEFAULT 20,
  max_attempts TINYINT UNSIGNED NOT NULL DEFAULT 3,
  retry_after_minutes SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS questions (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  exam_id INT UNSIGNED NOT NULL,
  question_text TEXT NOT NULL,
  options_json JSON NOT NULL,
  correct_option TINYINT UNSIGNED NOT NULL,
  explanation TEXT,
  sort_order SMALLINT UNSIGNED NOT NULL,
  CONSTRAINT fk_questions_exam FOREIGN KEY (exam_id) REFERENCES exams(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS attempts (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id INT UNSIGNED NOT NULL,
  exam_id INT UNSIGNED NOT NULL,
  score SMALLINT UNSIGNED NOT NULL,
  max_score SMALLINT UNSIGNED NOT NULL,
  correct_answers SMALLINT UNSIGNED NOT NULL,
  passed BOOLEAN NOT NULL,
  started_at DATETIME NOT NULL,
  finished_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  duration_seconds INT UNSIGNED NOT NULL DEFAULT 0,
  answers_json JSON,
  CONSTRAINT fk_attempts_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_attempts_exam FOREIGN KEY (exam_id) REFERENCES exams(id) ON DELETE CASCADE
);
